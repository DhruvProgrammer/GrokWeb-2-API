#!/usr/bin/env python3
"""
extract-everything.py — one-stop Grok setup wizard.

What it does
------------
1. Launches a stealth Chromium (CloakBrowser) so Cloudflare treats us
   as a real user.
2. Navigates to https://grok.com.
3. Waits for YOU to sign in / sign up (interactive — the script
   watches the page state and detects when sso + cf_clearance cookies
   appear).
4. Sends a test chat message to trigger x-statsig-id generation, then
   captures that header from the outgoing request.
5. Decodes the challenge:
       - bytes 0..48  = 49-byte static fingerprint (CHALLENGE_HEADER_HEX)
       - byte  69     = trailer constant                  (CHALLENGE_TRAILER)
6. Pulls all required cookies:
       sso, sso-rw, cf_clearance, __cf_bm
7. Writes a complete .env file (atomic write, chmod 600).
8. Runs a smoke test against the server (start, hit /health, stop).

Usage
-----
    # Live mode — opens a real browser, you sign in, .env gets written
    python scripts/extract-everything.py

    # Test mode — no browser, uses a stubbed session, perfect for CI
    python scripts/extract-everything.py --test

    # Custom env output path
    python scripts/extract-everything.py --env-file /tmp/my.env

    # Skip the smoke test
    python scripts/extract-everything.py --no-smoke

    # Point at a different server during the smoke test
    python scripts/extract-everything.py --server-port 5000

Exit codes
----------
    0  success
    1  user cancelled
    2  cookies not found (login not detected)
    3  challenge extraction failed
    4  .env write failed
    5  smoke test failed
"""

